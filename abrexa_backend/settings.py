# Check if MySQL service is listening on host:port before committing to MySQL
def is_mysql_available(host, port):
    import socket
    try:
        sock = socket.create_connection((host, int(port)), timeout=1)
        sock.close()
        return True
    except Exception:
        return False

if DB_ENGINE == 'mysql' and is_mysql_available(DB_HOST, DB_PORT):
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.mysql',
            'NAME': DB_NAME,
            'USER': DB_USER,
            'PASSWORD': DB_PASSWORD,
            'HOST': DB_HOST,
            'PORT': DB_PORT,
            'OPTIONS': {
                'init_command': "SET sql_mode='STRICT_TRANS_TABLES'",
                'charset': 'utf8mb4',
            },
        }
    }
